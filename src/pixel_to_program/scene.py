from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path

SIZE = 32
MAX_SHAPES = 4
COLORS = {"RED": (230, 45, 45), "BLUE": (40, 95, 225), "GREEN": (30, 170, 80)}
KINDS = {"RECT", "ELLIPSE"}


@dataclass(frozen=True)
class Shape:
    kind: str
    color: str
    x: int
    y: int
    width: int
    height: int

    def __post_init__(self):
        if (
            not isinstance(self.kind, str)
            or not isinstance(self.color, str)
            or self.kind not in KINDS
            or self.color not in COLORS
        ):
            raise ValueError("unsupported primitive or color")
        if any(type(value) is not int for value in (self.x, self.y, self.width, self.height)):
            raise ValueError("coordinates must be integers")
        if not (0 <= self.x < SIZE and 0 <= self.y < SIZE and 1 <= self.width <= SIZE and 1 <= self.height <= SIZE):
            raise ValueError("coordinates outside canvas")
        if self.x + self.width > SIZE or self.y + self.height > SIZE:
            raise ValueError("shape extends outside canvas")


@dataclass(frozen=True)
class Scene:
    shapes: tuple[Shape, ...]

    def __post_init__(self):
        if not isinstance(self.shapes, tuple) or len(self.shapes) > MAX_SHAPES:
            raise ValueError("scene requires a tuple of at most four primitives")
        if any(not isinstance(shape, Shape) for shape in self.shapes):
            raise ValueError("scene contains a non-shape")


def serialize(scene: Scene) -> str:
    commands = ["SCENE"]
    for shape in scene.shapes:
        commands.extend((shape.kind, shape.color, str(shape.x), str(shape.y), str(shape.width), str(shape.height)))
    return " ".join(commands + ["END"])


def parse_program(program: str) -> Scene:
    if not isinstance(program, str) or len(program) > 4096:
        raise ValueError("program must be a string of at most 4096 characters")
    tokens = program.split()
    if len(tokens) < 2 or tokens[0] != "SCENE" or tokens[-1] != "END":
        raise ValueError("program must begin SCENE and end END")
    body = tokens[1:-1]
    if len(body) % 6 or len(body) // 6 > MAX_SHAPES:
        raise ValueError("each shape needs kind, color, x, y, width, height; maximum four shapes")
    shapes = []
    for offset in range(0, len(body), 6):
        kind, color, *coordinates = body[offset : offset + 6]
        if any(not re.fullmatch(r"0|[1-9][0-9]?", value) for value in coordinates):
            raise ValueError("coordinates must be canonical unsigned decimal integers")
        shapes.append(Shape(kind, color, *(int(value) for value in coordinates)))
    return Scene(tuple(shapes))


def render_rgb(scene: Scene) -> bytes:
    pixels = bytearray([255] * (SIZE * SIZE * 3))
    for shape in scene.shapes:
        color = bytes(COLORS[shape.color])
        for y in range(shape.y, shape.y + shape.height):
            for x in range(shape.x, shape.x + shape.width):
                inside = shape.kind == "RECT"
                if shape.kind == "ELLIPSE":
                    dx = (x + 0.5 - shape.x - shape.width / 2) / (shape.width / 2)
                    dy = (y + 0.5 - shape.y - shape.height / 2) / (shape.height / 2)
                    inside = dx * dx + dy * dy <= 1
                if inside:
                    offset = (y * SIZE + x) * 3
                    pixels[offset : offset + 3] = color
    return bytes(pixels)


def render_svg(scene: Scene) -> str:
    elements = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">',
        '<rect width="32" height="32" fill="white"/>',
    ]
    for shape in scene.shapes:
        fill = "#" + "".join(f"{value:02x}" for value in COLORS[shape.color])
        if shape.kind == "RECT":
            elements.append(
                f'<rect x="{shape.x}" y="{shape.y}" width="{shape.width}" height="{shape.height}" fill="{fill}"/>'
            )
        else:
            elements.append(
                f'<ellipse cx="{shape.x + shape.width / 2:g}" cy="{shape.y + shape.height / 2:g}" rx="{shape.width / 2:g}" ry="{shape.height / 2:g}" fill="{fill}"/>'
            )
    return "\n".join(elements + ["</svg>"])


def ppm_bytes(scene: Scene) -> bytes:
    return b"P6\n32 32\n255\n" + render_rgb(scene)


def read_ppm(path: Path) -> bytes:
    if path.stat().st_size > 4096:
        raise ValueError("PPM exceeds the fixed 32x32 image budget")
    contents = path.read_bytes()
    header = b"P6\n32 32\n255\n"
    if not contents.startswith(header) or len(contents) != len(header) + SIZE * SIZE * 3:
        raise ValueError("expected a 32x32, 8-bit binary PPM generated by this project")
    return contents[len(header) :]


def reconstruction_metrics(expected: bytes, actual: bytes) -> dict:
    required = SIZE * SIZE * 3
    if len(expected) != required or len(actual) != required:
        raise ValueError("metric inputs must be fixed-size RGB rasters")
    expected_pixels = [expected[offset : offset + 3] for offset in range(0, required, 3)]
    actual_pixels = [actual[offset : offset + 3] for offset in range(0, required, 3)]
    foreground_a = {index for index, pixel in enumerate(expected_pixels) if pixel != b"\xff\xff\xff"}
    foreground_b = {index for index, pixel in enumerate(actual_pixels) if pixel != b"\xff\xff\xff"}
    union = foreground_a | foreground_b
    return {
        "exact_raster_match": expected == actual,
        "pixel_agreement": sum(a == b for a, b in zip(expected_pixels, actual_pixels)) / (SIZE * SIZE),
        "foreground_iou": len(foreground_a & foreground_b) / len(union) if union else 1.0,
        "rgb_mae": sum(abs(a - b) for a, b in zip(expected, actual)) / required / 255,
    }


def scene_hash(scene: Scene) -> str:
    return hashlib.sha256(serialize(scene).encode()).hexdigest()
